const DICT: Record<Lang, Record<I18nKey, string>> = { en, pt };

/** Tradução fora de componentes (ex.: no store / cliente da Azimuth). */
export function tr(lang: Lang, key: I18nKey, vars?: Record<string, string | number>): string {
  let s = DICT[lang]?.[key] ?? DICT[DEFAULT_LANG][key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function isLang(v: unknown): v is Lang {
  return typeof v === 'string' && (LANGS as string[]).includes(v);
}
